/**
 * Kraft's live automation flows: the first ten verbatim
 * (KraftScreens.dc.html:663-960), then ten more drawn on the same grid.
 * Coordinates are on the flow canvas (lib/flow.ts: FLOW_W × FLOW_H). A
 * node's `kind` marks an outcome ('on', accent) or a dead end ('off', the
 * alert red).
 */
export type FlowNode = { x: number; y: number; icon: Icon; name: string; sub: string; kind?: 'on' | 'off' }
export type FlowEdge = {
  f: number
  t: number
  from: [number, number]
  to: [number, number]
  /** Cubic control points; without them the edge is a straight line. */
  c?: [number, number, number, number]
  k?: 'dash' | 'dot'
  /** A travelling dot: seconds per trip, start delay in seconds, opacity. */
  ball?: [number, number, number?]
}
export type Flow = {
  label: string
  title: string
  blurb: string
  tags: string[]
  note: { x: number; y: number; text: string }
  nodes: FlowNode[]
  edges: FlowEdge[]
}

type N = [number, number, Icon, string, string, ('on' | 'off')?]
const nodes = (list: N[]): FlowNode[] => list.map(([x, y, icon, name, sub, kind]) => ({ x, y, icon, name, sub, kind }))

